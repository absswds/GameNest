"""Split LXGW WenKai into unicode-range pieces so a page only downloads the glyphs it shows.

Characters are ordered by how often they appear in the app's own text (public/, lang/, games/, bots/),
so the lobby and game UI only need the first few pieces; the rest of the font follows in codepoint order
for names and chat. Rerun after big text changes (new word banks, a new game):

    python scripts/split-font.py

Needs fonttools and brotli (python -m pip install --user fonttools brotli).
Writes public/assets/fonts/lxgw-wenkai/*.woff2 and font.css (imported at the top of public/style.css).
"""
import io
import os
import shutil
from collections import Counter
from concurrent.futures import ProcessPoolExecutor

from fontTools.subset import Options, Subsetter
from fontTools.ttLib import TTFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'scripts', 'font-src', 'lxgw-wenkai.woff2')
OUT = os.path.join(ROOT, 'public', 'assets', 'fonts', 'lxgw-wenkai')
TEXT_DIRS = ['public', 'lang', 'games', 'bots']
TEXT_EXT = ('.js', '.html', '.css', '.json')
FREQUENT_CHUNK = 300   # chars per piece for the characters the app itself uses
RARE_CHUNK = 1500      # chars per piece for the rest (only names and chat need these)


def corpus_counts():
    counts = Counter()
    for d in TEXT_DIRS:
        for base, _, files in os.walk(os.path.join(ROOT, d)):
            if 'assets' in base.replace('\\', '/').split('/'):
                continue
            for f in files:
                if f.endswith(TEXT_EXT):
                    with open(os.path.join(base, f), encoding='utf-8', errors='ignore') as fh:
                        counts.update(ch for ch in fh.read() if ord(ch) >= 0x80)
    return counts


def unicode_range(cps):
    cps = sorted(cps)
    parts, start, prev = [], cps[0], cps[0]
    for cp in cps[1:] + [None]:
        if cp is not None and cp == prev + 1:
            prev = cp
            continue
        parts.append('U+%X' % start if start == prev else 'U+%X-%X' % (start, prev))
        if cp is not None:
            start = prev = cp
    return ','.join(parts)


def build_piece(i, cps):
    opts = Options()
    opts.flavor = 'woff2'
    opts.layout_features = ['*']
    opts.name_IDs = ['*']
    opts.notdef_outline = True
    font = TTFont(SRC)
    sub = Subsetter(opts)
    sub.populate(unicodes=cps)
    sub.subset(font)
    path = os.path.join(OUT, 'wk-%02d.woff2' % i)
    font.save(path)
    return os.path.getsize(path)


def main():
    data = open(SRC, 'rb').read()
    cmap = set(TTFont(io.BytesIO(data)).getBestCmap())
    counts = corpus_counts()
    frequent = [ord(ch) for ch, _ in counts.most_common() if ord(ch) in cmap]
    ascii_ = [cp for cp in range(0x20, 0x7F) if cp in cmap]
    used = set(frequent) | set(ascii_)
    rare = sorted(cp for cp in cmap if cp not in used)

    chunks = [ascii_ + frequent[:FREQUENT_CHUNK]]
    chunks += [frequent[i:i + FREQUENT_CHUNK] for i in range(FREQUENT_CHUNK, len(frequent), FREQUENT_CHUNK)]
    chunks += [rare[i:i + RARE_CHUNK] for i in range(0, len(rare), RARE_CHUNK)]

    shutil.rmtree(OUT, ignore_errors=True)
    os.makedirs(OUT)
    # Each piece re-reads the whole font, so build them in parallel
    with ProcessPoolExecutor() as pool:
        sizes = list(pool.map(build_piece, range(len(chunks)), chunks))
    css = ['/* Generated by scripts/split-font.py from LXGW WenKai (OFL 1.1). Do not edit by hand. */']
    for i, cps in enumerate(chunks):
        print('wk-%02d.woff2 %4d chars %6.1f KB' % (i, len(cps), sizes[i] / 1024))
        css.append("@font-face{font-family:'LXGW WenKai';font-style:normal;font-weight:400 700;font-display:swap;"
                   "src:url('wk-%02d.woff2') format('woff2');unicode-range:%s}" % (i, unicode_range(cps)))
    total = sum(sizes)
    with open(os.path.join(OUT, 'font.css'), 'w', encoding='utf-8', newline='\n') as fh:
        fh.write('\n'.join(css) + '\n')
    print('%d pieces, %.1f MB, %d app characters' % (len(chunks), total / 1048576, len(frequent)))


if __name__ == '__main__':
    main()
